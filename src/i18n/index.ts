let _locale: Locale = 'zh-cn';

/** Resolve the effective locale from the VSCode UI language plus the optional config override. */
export function resolveLocale(vscodeLanguage: string | undefined, override?: string): Locale {
    if (override === 'zh-cn' || override === 'en') {return override;}
    return (vscodeLanguage || '').toLowerCase().startsWith('zh') ? 'zh-cn' : 'en';
}

export function setLocale(locale: Locale): void {
    _locale = locale;
}

export function getLocale(): Locale {
    return _locale;
}

/** Look up a string in the active locale; falls back to zh, then to the key itself. */
export function t(key: string, params?: I18nParams): string {
    let s = (_locale === 'en' ? en : zh)[key] ?? zh[key] ?? key;
    if (params) {
        for (const k of Object.keys(params)) {
            s = s.split('{' + k + '}').join(String(params[k]));
        }
    }
    return s;
}

/** The full active-locale dictionary, injected into the webview as window.I18N_STRINGS. */
export function webviewStrings(): Record<string, string> {
    return _locale === 'en' ? en : zh;
}
